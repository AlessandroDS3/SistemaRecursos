"""Contratos de acceso y persistencia de personas y cuentas."""

from typing import Protocol

from dominio.compartido.contratos import IRepositorioTransaccional
from dominio.gestion_personas_usuarios.acceso import CuentaAcceso
from dominio.gestion_personas_usuarios.persona import Persona


class IRepositorioAcceso(Protocol):
    def consultar_cuenta_por_usuario(self, nombre: str) -> CuentaAcceso | None: ...
    def consultar_cuenta_por_id(self, identificador: int) -> CuentaAcceso | None: ...
    def registrar_acceso(self, identificador: int) -> None: ...
    def consultar_fecha_actual(self): ...
    def crear_sesion(self, huella: str, id_usuario: int) -> None: ...
    def consultar_sesion(self, huella: str) -> dict | None: ...
    def registrar_actividad_sesion(self, huella: str) -> None: ...
    def cerrar_sesion(self, huella: str) -> None: ...


class IRepositorioCuenta(IRepositorioTransaccional, Protocol):
    def consultar_persona_para_cuenta(self, documento: str, bloquear=False) -> dict | None: ...
    def consultar_nombres_usuario(self, prefijo: str) -> list[str]: ...
    def consultar_id_por_nombre_usuario(self, nombre: str) -> int | None: ...
    def consultar_cuenta_para_cambiar_clave(self, identificador: int) -> dict | None: ...
    def consultar_cuenta(self, documento: str) -> dict | None: ...
    def consultar_cuentas_para_actualizar(self) -> list[dict]: ...
    def registrar_cuenta(self, documento: str, nombre: str, hash_clave: str) -> int: ...
    def registrar_primera_cuenta_administradora(
        self, persona: Persona, nombre: str, hash_clave: str
    ) -> int: ...
    def actualizar_cuenta(self, identificador: int, datos: dict) -> None: ...


class IRepositorioPersona(IRepositorioTransaccional, Protocol):
    def consultar_persona(self, documento: str, bloquear=False) -> dict | None: ...
    def consultar_personas(self, filtros: dict) -> dict: ...
    def guardar_persona(self, persona: Persona, documento_anterior: str | None = None) -> None: ...
    def consultar_cuentas_para_actualizar(self) -> list[dict]: ...
    def buscar_personas(self, termino: str) -> list[dict]: ...
