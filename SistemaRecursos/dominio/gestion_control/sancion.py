from typing import Protocol
from dominio.compartido.contratos import IRepositorioTransaccional
from dominio.compartido.validacion import Conflicto, texto


def validar_levantamiento(sancion, justificacion):
    if sancion['estado'] != 'ACTIVA':
        raise Conflicto('La sanción ya no está activa.')
    return texto(justificacion, 'Justificación', 255, True)


class IRepositorioSancion(IRepositorioTransaccional, Protocol):
    def consultar(self, identificador: int, bloquear=False) -> dict | None: ...
    def listar(self) -> list[dict]: ...
    def buscar_retraso(self, detalle: int) -> dict | None: ...
    def tiene_activas(self, documentos: list[str]) -> bool: ...
    def guardar_incidencia(self, detalle: int, tipo: str, descripcion: str, fecha) -> int: ...
    def guardar_sancion(self, incidencia: int, motivo: str, descripcion: str, fecha) -> int: ...
    def candidatos(self) -> list[dict]: ...
    def cargar_detalle(self, identificador: int) -> dict | None: ...
    def levantar(self, identificador: int, fecha, documento: str, justificacion: str): ...
