"""Contratos de persistencia de préstamos, reservas y ampliaciones."""

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Mapping, Protocol

from dominio.compartido.contratos import IRepositorioTransaccional
from dominio.gestion_control.contratos_control import IOperacionesSancion
from dominio.gestion_prestamos.ampliacion_prestamo import DatosParaValidarAmpliacion, PrestamoParaAmpliar, RestriccionesAmpliacion
from dominio.gestion_personas_usuarios.persona import PersonaParaPrestamo
from dominio.gestion_prestamos.prestamo import DatosParaValidarPrestamo, CupoArticulos, DetalleEntregaPlanificado, SolicitudPrestamo
from dominio.gestion_prestamos.reserva import (
    DatosParaValidarReserva,
    DetalleReserva,
    Reserva,
    ReservaEnCola,
)
from dominio.gestion_prestamos.solicitud_ampliacion import EstadoSolicitudAmpliacion, SolicitudAmpliacion


class IRepositorioPrestamo(IRepositorioTransaccional, Protocol):
    def consultar_politica_aplicada(self, identificador: int) -> dict | None: ...
    def consultar_resumen_prestamos(self, documento: str | None = None) -> dict: ...
    def consultar_prestamo_para_actualizar(self, identificador: int) -> dict | None: ...
    def consultar_condiciones_prestamo(self, documento: str) -> dict: ...
    @property
    def sanciones(self) -> IOperacionesSancion: ...
    def consultar_prestamo(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_prestamos(self, filtros: dict, documento: str | None = None) -> list[dict]: ...
    def consultar_datos_para_validar_prestamo(
        self, solicitud: SolicitudPrestamo, reserva_origen: int | None = None
    ) -> DatosParaValidarPrestamo: ...
    def consultar_cupo_persona(self, persona: PersonaParaPrestamo, reserva_origen: int | None = None) -> CupoArticulos: ...
    def es_participante(self, prestamo: int, documento: str) -> bool: ...
    def consultar_operador_autorizable(self, documento: str) -> bool: ...
    def guardar_autorizacion_propia(self, datos: dict) -> int: ...
    def consultar_autorizacion_propia(self, identificador, documento, accion, prestamo) -> dict | None: ...
    def consumir_autorizacion_propia(self, identificador: int, prestamo: int) -> None: ...
    def guardar_entrega_prestamo(self, solicitud: SolicitudPrestamo,
                                   plan: list[DetalleEntregaPlanificado], fecha: datetime) -> int: ...
    def registrar_devolucion(self, detalle: dict, devolucion, fecha, actor: str): ...
    def consultar_ultimo_movimiento_bien(self, bien: int) -> dict | None: ...
    def rectificar_devolucion(self, detalle: dict, movimiento: dict, motivo: str, actor: str) -> None: ...
    def cerrar_detalle_por_reposicion(self, detalle: int, fecha): ...
    def actualizar_estado_prestamo(self, prestamo: dict, nuevo: str, actor: str, motivo: str): ...
    def registrar_perdida_bien_material(
        self, prestamo: dict, detalle: dict, actor: str, motivo: str
    ): ...


class IRepositorioReserva(IRepositorioTransaccional, Protocol):
    def transaccion(self) -> AbstractContextManager['IRepositorioReserva']: ...
    def consultar_recursos_para_reserva(self, documento: str) -> list[dict]: ...
    def contar_reservas_pendientes(self, documento: str | None = None) -> int: ...
    @property
    def prestamos(self) -> IRepositorioPrestamo: ...
    def consultar_reserva(
        self, identificador: int, bloquear: bool = False
    ) -> DetalleReserva | None: ...
    def consultar_reservas(
        self, documento: str | None = None, filtros: Mapping[str, str] | None = None
    ) -> list[ReservaEnCola]: ...
    def guardar_nueva_reserva(self, reserva: Reserva) -> int: ...
    def actualizar_reserva(self, reserva: Reserva) -> None: ...
    def consultar_datos_para_validar_reserva(self, documento: str, recurso: int) -> DatosParaValidarReserva: ...
    def consultar_horario_y_plazos_de_reserva(self) -> dict | None: ...
    def bloquear_recurso(self, identificador: int) -> dict | None: ...
    def bloquear_persona(self, documento: str) -> None: ...
    def consultar_primera_reserva_en_espera(self, recurso: int, ahora: datetime) -> int | None: ...
    def consultar_bien_disponible(self, recurso: int) -> int | None: ...
    def cambiar_estado_bien_reservado(
        self, bien: int, estado: str, esperado: str, actor: str | None, reserva: int
    ): ...
    def consultar_reservas_vencidas(self) -> list[int]: ...


class IRepositorioAmpliacionPrestamo(IRepositorioTransaccional, Protocol):
    def transaccion(self) -> AbstractContextManager['IRepositorioAmpliacionPrestamo']: ...
    def consultar_restricciones_ampliacion(self, prestamo: PrestamoParaAmpliar,
                                         recurso: int) -> RestriccionesAmpliacion: ...
    def consultar_datos_para_validar_ampliacion(
        self, prestamo: int, detalle: int
    ) -> DatosParaValidarAmpliacion: ...
    def actualizar_plazo_prestamo(self, detalle: int, anterior: datetime, nueva: datetime) -> None: ...
    def registrar_solicitud_ampliacion(self, prestamo: int, detalle: int, solicitante: str,
                                       solicitud: SolicitudAmpliacion, fecha_anterior: datetime) -> int: ...
    def consultar_solicitud_ampliacion(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_solicitudes_ampliacion(self, estado=None, prestamo=None) -> list[dict]: ...
    def resolver_solicitud_ampliacion(self, identificador: int, estado: EstadoSolicitudAmpliacion, actor: str,
                                      nueva: datetime | None, observacion: str | None) -> None: ...
