"""Contratos de persistencia del catálogo y del inventario."""

from typing import Protocol

from dominio.compartido.contratos import IRepositorioTransaccional
from dominio.gestion_recursos.bien_material import BienMaterial
from dominio.gestion_recursos.recurso import Recurso


class IRepositorioRecurso(IRepositorioTransaccional, Protocol):
    def consultar_recursos(self, filtros: dict, contar_bienes=True) -> list[dict]: ...
    def consultar_disponibilidad(self) -> int: ...
    def consultar_recurso(self, identificador: int, bloquear=False) -> dict | None: ...
    def guardar_recurso(self, recurso: Recurso) -> int: ...
    def eliminar_recurso(self, identificador: int) -> None: ...
    def consultar_relaciones_recurso(self, identificador: int) -> dict: ...
    def consultar_bienes_materiales(self, filtros: dict) -> list[dict]: ...
    def consultar_categoria(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_relaciones_categoria(self, identificador: int) -> dict: ...
    def consultar_categorias(self) -> list[dict]: ...
    def guardar_categoria(self, nombre: str, descripcion: str, identificador=None) -> int: ...
    def guardar_bien_material(self, bien: BienMaterial) -> int: ...
    def eliminar_categoria(self, identificador: int) -> None: ...


class IRepositorioBienMaterial(IRepositorioTransaccional, Protocol):
    def consultar_bien_material(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_bienes_materiales(self, filtros: dict) -> list[dict]: ...
    def guardar_bien_material(self, bien: BienMaterial) -> int: ...
    def cambiar_estado_bien_material(
        self, identificador: int, anterior: str, nuevo: str, motivo: str, actor: str
    ) -> None: ...
    def consultar_prestamo_pendiente(self, identificador: int, bloquear=True) -> dict | None: ...
    def consultar_danio_pendiente(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_relaciones_bien_material(self, identificador: int, bloquear=True) -> dict: ...
    def eliminar_bien_material(self, identificador: int) -> None: ...
    def consultar_mantenimiento_abierto(self, identificador: int, bloquear=False) -> dict | None: ...
    def consultar_mantenimientos(self, identificador: int) -> list[dict]: ...
    def abrir_mantenimiento(self, identificador: int, apertura, estado_previo: str, actor: str) -> int: ...
    def cerrar_mantenimiento(self, id_mantenimiento: int, cierre, actor: str) -> None: ...
